export interface PresetKnowledgeData {
  subject: Subject
  chapters: Chapter[]
  cards: KnowledgeCard[]
}

export function buildPresetKnowledgeData(): PresetKnowledgeData {
  const subject: Subject = {
    id: PRESET_SUBJECT_ID,
    name: '日常食品与健康（预设体验）',
    description:
      '用于快速体验 RecallLab。主题提炼自《你是你吃出来的》，并按现行通用膳食建议筛除疾病治疗和过时定量表述；仅作健康教育，不替代医疗建议。',
    createdAt: PRESET_CREATED_AT,
    updatedAt: PRESET_CREATED_AT,
  }

  const chapters = CHAPTER_DEFINITIONS.map<Chapter>((chapter, index) => ({
    id: chapter.id,
    subjectId: PRESET_SUBJECT_ID,
    name: chapter.name,
    createdAt: PRESET_CREATED_AT + index,
    updatedAt: PRESET_CREATED_AT + index,
  }))

  const chapterByKey = new Map(CHAPTER_DEFINITIONS.map((chapter) => [chapter.key, chapter]))
  const cards: KnowledgeCard[] = []

  for (const chapter of CHAPTER_DEFINITIONS) {
    let previousCardId: string | undefined
    for (const [question, answer, tags, importance = 2] of CARD_GROUPS[chapter.key]) {
      const index = cards.length + 1
      const chapterDefinition = chapterByKey.get(chapter.key)!
      const id = `${PRESET_ID_PREFIX}card_${String(index).padStart(3, '0')}`
      cards.push({
        id,
        subjectId: PRESET_SUBJECT_ID,
        chapterId: chapterDefinition.id,
        parentCardId: previousCardId,
        question,
        answer,
        tags: [...tags],
        importance,
        status: 'active',
        note: `预设体验卡｜主题源自《你是你吃出来的》｜${chapterDefinition.name}｜仅作一般健康教育`,
        createdAt: PRESET_CREATED_AT + index,
        updatedAt: PRESET_CREATED_AT + index,
      })
      previousCardId = id
    }
  }

  if (cards.length !== 200) {
    throw new Error(`预设知识卡数量应为 200，当前为 ${cards.length}`)
  }

  return { subject, chapters, cards }
}
