export interface SeedancePresetKnowledgeData {
  subject: Subject
  chapters: Chapter[]
  cards: KnowledgeCard[]
}

export function buildSeedancePresetKnowledgeData(): SeedancePresetKnowledgeData {
  const subject: Subject = {
    id: SEEDANCE_PRESET_SUBJECT_ID,
    name: 'Doubao Seedance 2.0（默认）',
    description: '合并教程与提示词指南，按能力、API、多模态、任务模式、提示词、分镜和排障整理。',
    createdAt: CREATED_AT,
    updatedAt: CREATED_AT,
  }

  const chapters = CHAPTERS.map<Chapter>((chapter, index) => ({
    id: `${SEEDANCE_PRESET_ID_PREFIX}chapter_${String(index + 1).padStart(2, '0')}_${chapter.key}`,
    subjectId: SEEDANCE_PRESET_SUBJECT_ID,
    name: chapter.name,
    createdAt: CREATED_AT + index,
    updatedAt: CREATED_AT + index,
  }))

  const cards: KnowledgeCard[] = []
  CHAPTERS.forEach((chapter, chapterIndex) => {
    const chapterRecord = chapters[chapterIndex]!
    let previousCardId: string | undefined
    chapter.sections.forEach((section, sectionIndex) => {
      const sectionNumber = String(sectionIndex + 1).padStart(2, '0')
      const sectionId = `${chapterRecord.id}_section_${sectionNumber}`
      section.cards.forEach(([question, answer, tags, importance = 2]) => {
        const index = cards.length + 1
        const id = `${SEEDANCE_PRESET_ID_PREFIX}card_${String(index).padStart(3, '0')}`
        cards.push({
          id,
          subjectId: SEEDANCE_PRESET_SUBJECT_ID,
          chapterId: chapterRecord.id,
          sectionId,
          sectionTitle: `${sectionNumber} ${section.title}`,
          parentCardId: previousCardId,
          connection: previousCardId ? `承接“${chapter.name}”中的上一知识点继续学习。` : undefined,
          question,
          answer,
          tags: [...tags],
          importance,
          status: 'active',
          note: `默认知识库｜《Doubao Seedance 2.0 系列教程》《Doubao Seedance 2.0 系列提示词指南》｜${chapter.sourcePages}`,
          createdAt: CREATED_AT + index,
          updatedAt: CREATED_AT + index,
        })
        previousCardId = id
      })
    })
  })

  return { subject, chapters, cards }
}
